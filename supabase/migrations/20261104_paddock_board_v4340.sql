  'Creates (p_id null) or updates a paddock slot. Rejects overlaps in the same paddock and double-booked horses. Requires paddocks.manage.';
comment on function public.cce_paddock_delete_slot(bigint) is
  'Deletes a paddock slot. Requires paddocks.manage.';

