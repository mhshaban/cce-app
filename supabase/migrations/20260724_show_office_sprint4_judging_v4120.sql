create table if not exists public.show_office_class_judging (
  class_id bigint primary key references public.show_office_classes(id) on delete restrict,
  status text not null default 'Not Started',
  scoring_profile text not null default 'faults_then_time',
  ruleset_version text not null default 'CCE 2026',
  finalized_by uuid references auth.users(id) on delete set null,
  finalized_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint show_office_class_judging_status_check
    check (status in ('Not Started','Running','Finalized')),
  constraint show_office_class_judging_profile_check
    check (scoring_profile='faults_then_time'),
  constraint show_office_class_judging_ruleset_required
    check (length(trim(ruleset_version))>0),
  constraint show_office_class_judging_ruleset_length_check
    check (char_length(trim(ruleset_version))<=80),
  constraint show_office_class_judging_finalized_check check (
    (status='Finalized' and finalized_at is not null)
    or (status<>'Finalized' and finalized_at is null and finalized_by is null)
  )
);

create table if not exists public.show_office_entry_rounds (
  id bigint generated by default as identity primary key,
  result_ref uuid not null default gen_random_uuid() unique,
  entry_id bigint not null references public.show_office_entries(id) on delete restrict,
  phase text not null,
  time_ms integer,
  faults numeric(8,2),
  refusals smallint not null default 0,
  eliminated boolean not null default false,
  retired boolean not null default false,
  did_not_start boolean not null default false,
  row_version integer not null default 1,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint show_office_entry_rounds_phase_check
    check (phase in ('first_round','jump_off')),
  constraint show_office_entry_rounds_time_check
    check (time_ms is null or (time_ms>0 and time_ms<=86400000)),
  constraint show_office_entry_rounds_faults_check
    check (faults is null or (faults>=0 and faults<=999999.99)),
  constraint show_office_entry_rounds_refusals_check
    check (refusals between 0 and 9),
  constraint show_office_entry_rounds_version_check
    check (row_version>0),
  constraint show_office_entry_rounds_status_check check (
    (case when eliminated then 1 else 0 end)
    +(case when retired then 1 else 0 end)
    +(case when did_not_start then 1 else 0 end)<=1
  ),
  constraint show_office_entry_rounds_complete_check check (
    eliminated or retired or did_not_start
    or (time_ms is not null and faults is not null)
  ),
  constraint show_office_entry_rounds_dns_check check (
    not did_not_start or (time_ms is null and faults is null and refusals=0)
  )
);

