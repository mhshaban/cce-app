-- CCE StableOS v4.34.0 — Daily paddock schedule
-- Brings the "جدول إشغال البادوكات" page into the app. Each row of
-- paddock_slots is one time slot in one paddock (big / inner / outer):
--   * morning daily movement (Lunging / Free, 20 min, 9:00–12:00)
--   * evening sessions (45 min, 3:00–8:00) and reserved CCE stable sessions
-- Staff with paddocks.view see the whole board; paddocks.manage edits it.
-- Horse owners read it through cce_paddock_schedule(): their own horses'
-- slots come back with full details, every other taken slot comes back
-- only as "booked" — no horse, owner or stable number ever leaves the
-- database for a horse the caller does not own.
-- Safe to re-run: the board is seeded only while the table is empty.

begin;

do $$
begin
  if to_regclass('public.horses') is null
     or to_regclass('public.app_permissions') is null
     or to_regclass('public.role_permissions') is null
     or to_regprocedure('public.cce_has_permission(text)') is null then
    raise exception 'CCE unified member portal (v4.7.0) must be applied before the paddock schedule';
  end if;
end $$;

create table if not exists public.paddock_slots(
  id bigint generated by default as identity primary key,
  period text not null check (period in ('morning','evening')),
  paddock text not null check (paddock in ('big','inner','outer')),
  start_time time not null,
  end_time time not null,
  slot_type text not null default 'lunge' check (slot_type in ('lunge','session','stable')),
  horse_id bigint references public.horses(id) on delete set null,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_time>start_time),
  unique (paddock,start_time)
);

create index if not exists paddock_slots_horse_idx on public.paddock_slots(horse_id);

drop trigger if exists paddock_slots_touch on public.paddock_slots;
create trigger paddock_slots_touch before update on public.paddock_slots
for each row execute function public.cce_touch_updated_at();

insert into public.app_permissions(code,category,name_en,name_ar)
values
  ('paddocks.view','Horses','View paddock schedule','عرض جدول البادوكات'),
  ('paddocks.manage','Horses','Manage paddock schedule','إدارة جدول البادوكات')
on conflict (code) do nothing;

insert into public.role_permissions(role_id,permission_code,allowed)
select r.id,p.code,true
from public.app_roles r
join (values ('paddocks.view','manager'),('paddocks.view','reception'),('paddocks.view','staff'),
             ('paddocks.view','trainer'),('paddocks.manage','manager')) p(code,role) on p.role=r.code
on conflict (role_id,permission_code) do update set allowed=true;

alter table public.paddock_slots enable row level security;
revoke all on public.paddock_slots from anon;
grant select,insert,update,delete on public.paddock_slots to authenticated;

drop policy if exists cce_paddock_slots_select on public.paddock_slots;
create policy cce_paddock_slots_select on public.paddock_slots for select to authenticated
  using (public.cce_has_permission('paddocks.view') or public.cce_has_permission('paddocks.manage'));
drop policy if exists cce_paddock_slots_insert on public.paddock_slots;
create policy cce_paddock_slots_insert on public.paddock_slots for insert to authenticated
  with check (public.cce_has_permission('paddocks.manage'));
drop policy if exists cce_paddock_slots_update on public.paddock_slots;
create policy cce_paddock_slots_update on public.paddock_slots for update to authenticated
  using (public.cce_has_permission('paddocks.manage'))
  with check (public.cce_has_permission('paddocks.manage'));
drop policy if exists cce_paddock_slots_delete on public.paddock_slots;
create policy cce_paddock_slots_delete on public.paddock_slots for delete to authenticated
  using (public.cce_has_permission('paddocks.manage'));

-- The board as the caller may see it. Staff get every detail; an owner gets
-- details only for horses they own (same rule as cce_member_owner_horses)
-- and a bare "booked" flag for every other taken slot.
create or replace function public.cce_paddock_schedule()
returns jsonb
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
declare
  v_full boolean:=public.cce_has_permission('paddocks.view') or public.cce_has_permission('paddocks.manage');
  v_owner_view boolean:=public.cce_has_permission('owner.horses.view');
  v_owner text;
begin
  if not v_full and not v_owner_view then
    raise exception 'Permission denied';
  end if;
  select nullif(trim(owner_name),'') into v_owner from public.profiles where id=auth.uid() and is_active=true;

  return coalesce((
    select jsonb_agg(r.j order by r.j->>'period' desc, r.j->>'paddock', r.j->>'start_time')
    from (
      select case
        when v_full or s.mine then jsonb_build_object(
          'id',s.id,'period',s.period,'paddock',s.paddock,
          'start_time',to_char(s.start_time,'HH24:MI'),'end_time',to_char(s.end_time,'HH24:MI'),
          'slot_type',s.slot_type,'booked',s.horse_id is not null or s.slot_type='stable','mine',s.mine,
          'horse_id',s.horse_id,'horse_name',trim(h.horse_name),'owner',h.owner,'stable_no',h.stable_no,
          'note',s.note)
        else jsonb_build_object(
          'id',s.id,'period',s.period,'paddock',s.paddock,
          'start_time',to_char(s.start_time,'HH24:MI'),'end_time',to_char(s.end_time,'HH24:MI'),
          'booked',s.horse_id is not null or s.slot_type='stable','mine',false)
      end as j
      from (
        select ps.*,
          coalesce(ps.horse_id is not null and exists(
            select 1 from public.horses oh
            where oh.id=ps.horse_id
              and (oh.owner_profile_id=auth.uid()
                or (oh.owner_profile_id is null and v_owner is not null and lower(trim(oh.owner))=lower(v_owner)))
          ),false) as mine
        from public.paddock_slots ps
      ) s
      left join public.horses h on h.id=s.horse_id
    ) r
  ),'[]'::jsonb);
end;
$$;

revoke all on function public.cce_paddock_schedule() from public,anon;
grant execute on function public.cce_paddock_schedule() to authenticated;

