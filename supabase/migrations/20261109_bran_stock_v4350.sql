-- CCE StableOS v4.35.0 — Bran stock per owner account
-- The stable buys a fixed number of Bran bags a month (100) for every horse.
-- An owner account (one or more owners sharing a store, e.g. Abdulla & Hashem)
-- gets a monthly share in proportion to its Available horses; bags issued
-- beyond the share come out of bags the owners bought themselves and left
-- in the store. feed_ledger records issues and owner purchases;
-- cce_feed_summary(month) works out, per account and month: the share,
-- bags issued, bags taken from the owners' own stock and the running own
-- balance. Managers (feed.manage) record entries; an owner sees only the
-- account their horses belong to. Safe to re-run.

begin;

do $$
begin
  if to_regclass('public.horses') is null
     or to_regclass('public.app_permissions') is null
     or to_regprocedure('public.cce_has_permission(text)') is null then
    raise exception 'CCE unified member portal (v4.7.0) must be applied before Bran stock';
  end if;
end $$;

create table if not exists public.feed_settings(
  id bigint generated by default as identity primary key,
  item text not null unique,
  stable_monthly_bags numeric(8,2) not null check (stable_monthly_bags>=0),
  updated_at timestamptz not null default now()
);

create table if not exists public.feed_accounts(
  id bigint generated by default as identity primary key,
  item text not null default 'Bran',
  name text not null,
  owners text[] not null default '{}',
  monthly_allocation numeric(8,2) check (monthly_allocation is null or monthly_allocation>=0),
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (item,name)
);

create table if not exists public.feed_ledger(
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.feed_accounts(id) on delete cascade,
  entry_date date not null,
  kind text not null check (kind in ('issue','purchase','adjust')),
  qty numeric(8,2) not null check (qty<>0 and (kind='adjust' or qty>0)),
  note text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists feed_ledger_account_date_idx on public.feed_ledger(account_id,entry_date);

drop trigger if exists feed_accounts_touch on public.feed_accounts;
create trigger feed_accounts_touch before update on public.feed_accounts
for each row execute function public.cce_touch_updated_at();
drop trigger if exists feed_settings_touch on public.feed_settings;
create trigger feed_settings_touch before update on public.feed_settings
for each row execute function public.cce_touch_updated_at();

insert into public.app_permissions(code,category,name_en,name_ar)
values
  ('feed.view','Horses','View Bran stock','عرض مخزون البران'),
  ('feed.manage','Horses','Manage Bran stock','إدارة مخزون البران')
on conflict (code) do nothing;
insert into public.role_permissions(role_id,permission_code,allowed)
select r.id,p.code,true
from public.app_roles r
join (values ('feed.view','manager'),('feed.manage','manager')) p(code,role) on p.role=r.code
on conflict (role_id,permission_code) do update set allowed=true;

