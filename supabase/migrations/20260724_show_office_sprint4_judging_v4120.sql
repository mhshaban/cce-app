create or replace function public.cce_restore_show_office_judging_data(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_judging jsonb:=coalesce(p_payload->'judging','[]'::jsonb);
  v_scores jsonb:=coalesce(p_payload->'scores','[]'::jsonb);
  v_row jsonb;
  v_date date;
  v_class_id bigint;
  v_entry_id bigint;
  v_ref uuid;
  v_phase text;
  v_flags integer;
  v_inserted_id bigint;
  v_judging_total integer:=0; v_judging_imported integer:=0; v_judging_duplicates integer:=0;
  v_score_total integer:=0; v_score_imported integer:=0; v_score_duplicates integer:=0;
begin
  if jsonb_typeof(v_judging)<>'array' or jsonb_typeof(v_scores)<>'array' then
    raise exception 'Show Office judging and scores must be JSON arrays' using errcode='22023';
  end if;
  v_judging_total:=jsonb_array_length(v_judging);
  v_score_total:=jsonb_array_length(v_scores);
  if v_judging_total+v_score_total>0
     and not public.cce_has_permission('show_office.judging.score') then
    raise exception 'Permission denied: Show Office judging score permission is required'
      using errcode='42501';
  end if;
  if exists(
    select 1 from jsonb_array_elements(v_judging) item
    where item->>'status'='Finalized'
  ) and not public.cce_has_permission('show_office.judging.finalize') then
    raise exception 'Permission denied: Show Office judging finalize permission is required'
      using errcode='42501';
  end if;

  for v_row in select value from jsonb_array_elements(v_judging) loop
    if jsonb_typeof(v_row)<>'object' then
      raise exception 'Show Office backup judging record must be an object' using errcode='22023';
    end if;
    begin v_date:=(v_row->>'competition_date')::date; exception when others then
      raise exception 'Show Office backup judging record has an invalid date' using errcode='22023'; end;
    if coalesce(v_row->>'competition_date','')!~'^\d{4}-\d{2}-\d{2}$'
       or to_char(v_date,'YYYY-MM-DD')<>v_row->>'competition_date'
       or length(trim(coalesce(v_row->>'competition_name','')))=0
       or length(trim(coalesce(v_row->>'class_number','')))=0
       or v_row->>'status' not in ('Not Started','Running','Finalized')
       or coalesce(v_row->>'scoring_profile','faults_then_time')<>'faults_then_time'
       or length(trim(coalesce(v_row->>'ruleset_version','CCE 2026')))=0
       or char_length(trim(coalesce(v_row->>'ruleset_version','CCE 2026')))>80 then
      raise exception 'Show Office backup judging record is invalid' using errcode='22023';
    end if;
    select cl.id into v_class_id
    from public.show_office_classes cl
    join public.show_office_competitions c on c.id=cl.competition_id
    where lower(trim(c.competition_name))=lower(trim(v_row->>'competition_name'))
      and c.competition_date=v_date
      and lower(trim(cl.class_number))=lower(trim(v_row->>'class_number'));
    if v_class_id is null then
      raise exception 'Show Office backup judging record references an unavailable class'
        using errcode='23503';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_class_judging(
      class_id,status,scoring_profile,ruleset_version,finalized_by,finalized_at
    ) values(
      v_class_id,v_row->>'status','faults_then_time',
      trim(coalesce(v_row->>'ruleset_version','CCE 2026')),
      case when v_row->>'status'='Finalized' then auth.uid() else null end,
      case when v_row->>'status'='Finalized' then now() else null end
    ) on conflict do nothing returning class_id into v_inserted_id;
    if v_inserted_id is null then v_judging_duplicates:=v_judging_duplicates+1;
    else v_judging_imported:=v_judging_imported+1; end if;
  end loop;

  for v_row in select value from jsonb_array_elements(v_scores) loop
    if jsonb_typeof(v_row)<>'object' then
      raise exception 'Show Office backup score must be an object' using errcode='22023';
    end if;
    begin
      v_ref:=(v_row->>'result_ref')::uuid;
      v_entry_id=null;
      v_phase:=lower(trim(v_row->>'phase'));
    exception when others then
      raise exception 'Show Office backup score has invalid references' using errcode='22023';
    end;
    if v_phase not in ('first_round','jump_off')
       or jsonb_typeof(v_row->'refusals')<>'number'
       or (v_row->>'refusals')::numeric<>trunc((v_row->>'refusals')::numeric)
       or ((v_row->>'refusals')::integer not between 0 and 9) then
      raise exception 'Show Office backup score has invalid phase or refusals' using errcode='22023';
    end if;
    if (v_row?'eliminated' and jsonb_typeof(v_row->'eliminated')<>'boolean')
       or (v_row?'retired' and jsonb_typeof(v_row->'retired')<>'boolean')
       or (v_row?'did_not_start' and jsonb_typeof(v_row->'did_not_start')<>'boolean') then
      raise exception 'Show Office backup score flags must be boolean' using errcode='22023';
    end if;
    v_flags:=(case when coalesce((v_row->>'eliminated')::boolean,false) then 1 else 0 end)
      +(case when coalesce((v_row->>'retired')::boolean,false) then 1 else 0 end)
      +(case when coalesce((v_row->>'did_not_start')::boolean,false) then 1 else 0 end);
    if v_flags>1 then raise exception 'Show Office backup score has conflicting statuses' using errcode='22023'; end if;
    if v_flags=0 and (
      jsonb_typeof(v_row->'time_ms')<>'number'
      or (v_row->>'time_ms')::numeric<>trunc((v_row->>'time_ms')::numeric)
      or (v_row->>'time_ms')::integer<=0 or (v_row->>'time_ms')::integer>86400000
      or jsonb_typeof(v_row->'faults')<>'number'
      or (v_row->>'faults')::numeric<0 or (v_row->>'faults')::numeric>999999.99
    ) then
      raise exception 'Show Office backup completed score has invalid time or faults' using errcode='22023';
    end if;
    select id into v_entry_id from public.show_office_entries
    where entry_ref=(v_row->>'entry_ref')::uuid;
    if v_entry_id is null then
      raise exception 'Show Office backup score references an unavailable entry'
        using errcode='23503';
    end if;
    if v_phase='jump_off' and not exists(
      select 1 from public.show_office_entries e
      join public.show_office_classes cl on cl.id=e.class_id
      where e.id=v_entry_id and cl.jump_off
    ) then
      raise exception 'Show Office backup score uses Jump-Off for an incompatible class'
        using errcode='22023';
    end if;
    if not exists(
      select 1
      from public.show_office_entries e
      join public.show_office_class_judging j on j.class_id=e.class_id
      where e.id=v_entry_id
    ) then
      raise exception 'Show Office backup score requires a judging record for its class'
        using errcode='22023';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_entry_rounds(
      result_ref,entry_id,phase,time_ms,faults,refusals,eliminated,retired,did_not_start
    ) values(
      v_ref,v_entry_id,v_phase,
      case when v_flags=0 then (v_row->>'time_ms')::integer else null end,
      case when v_flags=0 then (v_row->>'faults')::numeric else null end,
      case when coalesce((v_row->>'did_not_start')::boolean,false)
        then 0 else (v_row->>'refusals')::smallint end,
      coalesce((v_row->>'eliminated')::boolean,false),
      coalesce((v_row->>'retired')::boolean,false),
      coalesce((v_row->>'did_not_start')::boolean,false)
    ) on conflict do nothing returning id into v_inserted_id;
    if v_inserted_id is null then v_score_duplicates:=v_score_duplicates+1;
    else v_score_imported:=v_score_imported+1; end if;
  end loop;

  if exists(
    select 1 from public.show_office_entry_rounds jo
    join public.show_office_entries e on e.id=jo.entry_id
    left join public.show_office_entry_rounds fr
      on fr.entry_id=e.id and fr.phase='first_round'
    where jo.phase='jump_off'
      and (fr.id is null or fr.eliminated or fr.retired or fr.did_not_start)
  ) then
    raise exception 'Show Office restored Jump-Off score requires a valid first round'
      using errcode='22023';
  end if;
  if exists(
    select 1 from public.show_office_class_judging j
    left join public.show_office_entries e on e.class_id=j.class_id
    left join public.show_office_entry_rounds r
      on r.entry_id=e.id and r.phase='first_round'
    where j.status='Finalized'
    group by j.class_id
    having count(e.id)=0 or count(e.id) filter(where r.id is null)>0
  ) then
    raise exception 'Show Office restored finalized class has unscored entries'
      using errcode='22023';
  end if;
  return jsonb_build_object(
    'total',v_judging_total+v_score_total,
    'imported',v_judging_imported+v_score_imported,
    'duplicates',v_judging_duplicates+v_score_duplicates,
    'invalid',0,
    'entities',jsonb_build_object(
      'judging',jsonb_build_object(
        'total',v_judging_total,'imported',v_judging_imported,
        'duplicates',v_judging_duplicates,'invalid',0
      ),
      'scores',jsonb_build_object(
        'total',v_score_total,'imported',v_score_imported,
        'duplicates',v_score_duplicates,'invalid',0
      )
    )
  );
end;
$$;

revoke all on function public.cce_restore_show_office_judging_data(jsonb)
  from public,anon,authenticated;

create or replace function public.cce_restore_show_office_module(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_core jsonb;
  v_judging jsonb;
begin
  if p_payload is null or jsonb_typeof(p_payload)<>'object' then
    raise exception 'Show Office restore payload must be a JSON object' using errcode='22023';
  end if;
  select public.cce_restore_show_office_through_entries(p_payload) into v_core;
  select public.cce_restore_show_office_judging_data(p_payload) into v_judging;
  return jsonb_build_object(
    'module','showOffice',
    'total',(v_core->>'total')::integer+(v_judging->>'total')::integer,
    'imported',(v_core->>'imported')::integer+(v_judging->>'imported')::integer,
    'duplicates',(v_core->>'duplicates')::integer+(v_judging->>'duplicates')::integer,
    'invalid',0,
    'entities',(v_core->'entities')||(v_judging->'entities')
  );
end;
$$;

