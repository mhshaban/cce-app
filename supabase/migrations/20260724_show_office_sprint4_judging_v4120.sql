create or replace function public.cce_show_office_judging_context()
returns table(
  competition_id bigint,competition_name text,competition_date date,competition_status text,
  class_id bigint,class_number text,class_name text,sort_order integer,height_cm smallint,
  competition_type text,allowed_time_seconds integer,time_limit_seconds integer,jump_off boolean,
  judging_status text,scoring_profile text,ruleset_version text,finalized_at timestamptz,
  entry_count bigint,scored_count bigint
)
language plpgsql
stable
security definer
set search_path=public
as $$
begin
  if not (
    public.cce_has_permission('show_office.view')
    or public.cce_has_permission('show_office.judging.view')
    or public.cce_has_permission('show_office.judging.score')
    or public.cce_has_permission('show_office.judging.finalize')
    or public.cce_has_permission('show_office.judging.reopen')
  ) then
    raise exception 'Permission denied: Show Office judging view permission is required'
      using errcode='42501';
  end if;
  return query
  select
    c.id,c.competition_name,c.competition_date,c.status,
    cl.id,cl.class_number,cl.class_name,cl.sort_order,cl.height_cm,
    cl.competition_type,cl.allowed_time_seconds,cl.time_limit_seconds,cl.jump_off,
    coalesce(j.status,'Not Started'),coalesce(j.scoring_profile,'faults_then_time'),
    coalesce(j.ruleset_version,'CCE 2026'),j.finalized_at,
    count(distinct e.id),
    count(distinct r.entry_id) filter(where r.phase='first_round')
  from public.show_office_classes cl
  join public.show_office_competitions c on c.id=cl.competition_id
  left join public.show_office_class_judging j on j.class_id=cl.id
  left join public.show_office_entries e on e.class_id=cl.id
  left join public.show_office_entry_rounds r on r.entry_id=e.id
  group by c.id,c.competition_name,c.competition_date,c.status,
    cl.id,cl.class_number,cl.class_name,cl.sort_order,cl.height_cm,
    cl.competition_type,cl.allowed_time_seconds,cl.time_limit_seconds,cl.jump_off,
    j.status,j.scoring_profile,j.ruleset_version,j.finalized_at
  order by c.competition_date desc,c.id desc,cl.sort_order,cl.id;
end;
$$;

create or replace function public.cce_show_office_judge_panel(p_class_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare
  v_class jsonb;
  v_rows jsonb;
  v_jump_off boolean;
begin
  if not (
    public.cce_has_permission('show_office.view')
    or public.cce_has_permission('show_office.judging.view')
    or public.cce_has_permission('show_office.judging.score')
    or public.cce_has_permission('show_office.judging.finalize')
    or public.cce_has_permission('show_office.judging.reopen')
  ) then
    raise exception 'Permission denied: Show Office judging view permission is required'
      using errcode='42501';
  end if;
  select cl.jump_off,jsonb_build_object(
    'competition_id',c.id,'competition_name',c.competition_name,
    'competition_date',c.competition_date,'competition_status',c.status,
    'class_id',cl.id,'class_number',cl.class_number,'class_name',cl.class_name,
    'height_cm',cl.height_cm,'competition_type',cl.competition_type,
    'allowed_time_seconds',cl.allowed_time_seconds,
    'time_limit_seconds',cl.time_limit_seconds,'jump_off',cl.jump_off,
    'judging_status',coalesce(j.status,'Not Started'),
    'scoring_profile',coalesce(j.scoring_profile,'faults_then_time'),
    'ruleset_version',coalesce(j.ruleset_version,'CCE 2026'),
    'finalized_at',j.finalized_at
  ) into v_jump_off,v_class
  from public.show_office_classes cl
  join public.show_office_competitions c on c.id=cl.competition_id
  left join public.show_office_class_judging j on j.class_id=cl.id
  where cl.id=p_class_id;
  if v_class is null then
    raise exception 'Show Office class was not found' using errcode='P0002';
  end if;

  with base as (
    select
      e.id as entry_id,e.entry_ref,e.start_number,
      r.rider_name,h.horse_name,s.stable_name,
      fr.id as fr_id,fr.result_ref as fr_ref,fr.time_ms as fr_time,fr.faults as fr_faults,
      fr.refusals as fr_refusals,fr.eliminated as fr_eliminated,
      fr.retired as fr_retired,fr.did_not_start as fr_dns,fr.row_version as fr_version,
      jo.id as jo_id,jo.result_ref as jo_ref,jo.time_ms as jo_time,jo.faults as jo_faults,
      jo.refusals as jo_refusals,jo.eliminated as jo_eliminated,
      jo.retired as jo_retired,jo.did_not_start as jo_dns,jo.row_version as jo_version,
      (
        fr.id is not null
        and not fr.eliminated and not fr.retired and not fr.did_not_start
        and (jo.id is null or (not jo.eliminated and not jo.retired and not jo.did_not_start))
      ) as rankable
    from public.show_office_entries e
    join public.show_office_riders r on r.id=e.rider_id
    join public.show_office_horses h on h.id=e.horse_id
    left join public.show_office_stables s on s.id=e.stable_id
    left join public.show_office_entry_rounds fr
      on fr.entry_id=e.id and fr.phase='first_round'
    left join public.show_office_entry_rounds jo
      on jo.entry_id=e.id and jo.phase='jump_off'
    where e.class_id=p_class_id
  ), ranked as (
    select base.*,
      case when rankable then rank() over(order by
        case
          when rankable and v_jump_off and jo_id is not null then 0
          when rankable then 1 else 9
        end,
        case when v_jump_off and jo_id is not null then jo_faults else fr_faults end,
        case when v_jump_off and jo_id is not null then jo_time else fr_time end
      ) end as place_number
    from base
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'entry_id',entry_id,'entry_ref',entry_ref,'start_number',start_number,
    'rider_name',rider_name,'horse_name',horse_name,'stable_name',stable_name,
    'placing',place_number,
    'first_round',case when fr_id is null then null else jsonb_build_object(
      'id',fr_id,'result_ref',fr_ref,'phase','first_round','time_ms',fr_time,
      'faults',fr_faults,'refusals',fr_refusals,'eliminated',fr_eliminated,
      'retired',fr_retired,'did_not_start',fr_dns,'row_version',fr_version
    ) end,
    'jump_off',case when jo_id is null then null else jsonb_build_object(
      'id',jo_id,'result_ref',jo_ref,'phase','jump_off','time_ms',jo_time,
      'faults',jo_faults,'refusals',jo_refusals,'eliminated',jo_eliminated,
      'retired',jo_retired,'did_not_start',jo_dns,'row_version',jo_version
    ) end
  ) order by start_number,entry_id),'[]'::jsonb) into v_rows
  from ranked;
  return jsonb_build_object('class',v_class,'rows',v_rows);
end;
$$;

create or replace function public.cce_save_show_office_score(
  p_entry_id bigint,p_phase text,p_time_ms integer,p_faults numeric,p_refusals smallint,
  p_eliminated boolean,p_retired boolean,p_did_not_start boolean,
  p_expected_version integer default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_phase text:=lower(trim(coalesce(p_phase,'')));
  v_class_id bigint;
  v_jump_off boolean;
  v_competition_status text;
  v_judging_status text;
  v_existing_id bigint;
  v_existing_version integer;
  v_flags integer;
  v_result jsonb;
begin
  if not public.cce_has_permission('show_office.judging.score') then
    raise exception 'Permission denied: Show Office judging score permission is required'
      using errcode='42501';
  end if;
  select cl.id,cl.jump_off,c.status
    into v_class_id,v_jump_off,v_competition_status
  from public.show_office_entries e
  join public.show_office_classes cl on cl.id=e.class_id
  join public.show_office_competitions c on c.id=cl.competition_id
  where e.id=p_entry_id;
  if v_class_id is null then raise exception 'Show Office entry was not found' using errcode='P0002'; end if;
  if v_competition_status<>'Running' then
    raise exception 'Competition must be Running before scores can be recorded' using errcode='22023';
  end if;
  if v_phase not in ('first_round','jump_off') then
    raise exception 'Score phase must be first_round or jump_off' using errcode='22023';
  end if;
  if v_phase='jump_off' and not v_jump_off then
    raise exception 'This class does not allow a Jump-Off' using errcode='22023';
  end if;
  v_flags:=(case when coalesce(p_eliminated,false) then 1 else 0 end)
    +(case when coalesce(p_retired,false) then 1 else 0 end)
    +(case when coalesce(p_did_not_start,false) then 1 else 0 end);
  if v_flags>1 then
    raise exception 'Eliminated, Retired and DNS are mutually exclusive' using errcode='22023';
  end if;
  if coalesce(p_refusals,0)<0 or coalesce(p_refusals,0)>9 then
    raise exception 'Refusals must be between 0 and 9' using errcode='22023';
  end if;
  if v_flags=0 and (
    p_time_ms is null or p_time_ms<=0 or p_time_ms>86400000
    or p_faults is null or p_faults<0 or p_faults>999999.99
  ) then
    raise exception 'A completed score requires a valid time and faults value' using errcode='22023';
  end if;
  if v_phase='jump_off' and not exists(
    select 1 from public.show_office_entry_rounds
    where entry_id=p_entry_id and phase='first_round'
      and not eliminated and not retired and not did_not_start
  ) then
    raise exception 'A valid first-round score is required before the Jump-Off' using errcode='22023';
  end if;

  insert into public.show_office_class_judging(class_id,status)
  values(v_class_id,'Running') on conflict(class_id) do nothing;
  select status into v_judging_status
  from public.show_office_class_judging where class_id=v_class_id for update;
  if v_judging_status='Finalized' then
    raise exception 'Class results are finalized and locked' using errcode='55000';
  end if;
  if v_judging_status='Not Started' then
    update public.show_office_class_judging set status='Running' where class_id=v_class_id;
  end if;

  select id,row_version into v_existing_id,v_existing_version
  from public.show_office_entry_rounds
  where entry_id=p_entry_id and phase=v_phase
  for update;
  if v_existing_id is null then
    if coalesce(p_expected_version,0)<>0 then
      raise exception 'Score changed on another device; reload before saving'
        using errcode='40001';
    end if;
    insert into public.show_office_entry_rounds(
      entry_id,phase,time_ms,faults,refusals,eliminated,retired,did_not_start
    ) values(
      p_entry_id,v_phase,
      case when v_flags=0 then p_time_ms else null end,
      case when v_flags=0 then p_faults else null end,
      case when coalesce(p_did_not_start,false) then 0 else coalesce(p_refusals,0) end,
      coalesce(p_eliminated,false),coalesce(p_retired,false),coalesce(p_did_not_start,false)
    ) returning id into v_existing_id;
  else
    if p_expected_version is null or p_expected_version<>v_existing_version then
      raise exception 'Score changed on another device; reload before saving'
        using errcode='40001';
    end if;
    update public.show_office_entry_rounds set
      time_ms=case when v_flags=0 then p_time_ms else null end,
      faults=case when v_flags=0 then p_faults else null end,
      refusals=case when coalesce(p_did_not_start,false) then 0 else coalesce(p_refusals,0) end,
      eliminated=coalesce(p_eliminated,false),
      retired=coalesce(p_retired,false),
      did_not_start=coalesce(p_did_not_start,false)
    where id=v_existing_id and row_version=p_expected_version;
    if not found then
      raise exception 'Score changed on another device; reload before saving'
        using errcode='40001';
    end if;
  end if;
  select to_jsonb(r) into strict v_result
  from public.show_office_entry_rounds r where r.id=v_existing_id;
  return v_result;
end;
$$;

create or replace function public.cce_reset_show_office_score(
  p_entry_id bigint,p_phase text,p_expected_version integer
)
returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare
  v_phase text:=lower(trim(coalesce(p_phase,'')));
  v_class_id bigint;
  v_status text;
  v_competition_status text;
begin
  if not public.cce_has_permission('show_office.judging.score') then
    raise exception 'Permission denied: Show Office judging score permission is required'
      using errcode='42501';
  end if;
  if v_phase not in ('first_round','jump_off') then
    raise exception 'Score phase must be first_round or jump_off' using errcode='22023';
  end if;
  select e.class_id,coalesce(j.status,'Not Started'),c.status
    into v_class_id,v_status,v_competition_status
  from public.show_office_entries e
  join public.show_office_classes cl on cl.id=e.class_id
  join public.show_office_competitions c on c.id=cl.competition_id
  left join public.show_office_class_judging j on j.class_id=e.class_id
  where e.id=p_entry_id;
  if v_class_id is null then raise exception 'Show Office entry was not found' using errcode='P0002'; end if;
  if v_competition_status<>'Running' then
    raise exception 'Competition must be Running before scores can be reset' using errcode='22023';
  end if;
  if v_status='Finalized' then raise exception 'Class results are finalized and locked' using errcode='55000'; end if;
  if v_phase='first_round' and exists(
    select 1 from public.show_office_entry_rounds
    where entry_id=p_entry_id and phase='jump_off'
  ) then
    raise exception 'Reset the Jump-Off score before resetting the first round' using errcode='55000';
  end if;
  delete from public.show_office_entry_rounds
  where entry_id=p_entry_id and phase=v_phase and row_version=p_expected_version;
  if not found then
    raise exception 'Score changed on another device; reload before resetting'
      using errcode='40001';
  end if;
  if not exists(
    select 1 from public.show_office_entry_rounds r
    join public.show_office_entries e on e.id=r.entry_id
    where e.class_id=v_class_id
  ) then
    update public.show_office_class_judging set status='Not Started'
    where class_id=v_class_id;
  end if;
  return true;
end;
$$;

create or replace function public.cce_finalize_show_office_class(p_class_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_entry_count bigint;
  v_missing bigint;
  v_competition_status text;
  v_result jsonb;
begin
  if not public.cce_has_permission('show_office.judging.finalize') then
    raise exception 'Permission denied: Show Office judging finalize permission is required'
      using errcode='42501';
  end if;
  select c.status,count(e.id),
    count(e.id) filter(where r.id is null)
  into v_competition_status,v_entry_count,v_missing
  from public.show_office_classes cl
  join public.show_office_competitions c on c.id=cl.competition_id
  left join public.show_office_entries e on e.class_id=cl.id
  left join public.show_office_entry_rounds r
    on r.entry_id=e.id and r.phase='first_round'
  where cl.id=p_class_id
  group by c.status;
  if v_competition_status is null then raise exception 'Show Office class was not found' using errcode='P0002'; end if;
  if v_competition_status<>'Running' then
    raise exception 'Competition must be Running before results can be finalized' using errcode='22023';
  end if;
  if v_entry_count=0 then raise exception 'A class without entries cannot be finalized' using errcode='22023'; end if;
  if v_missing>0 then
    raise exception 'Every entry requires a first-round result before finalization' using errcode='22023';
  end if;
  insert into public.show_office_class_judging(
    class_id,status,scoring_profile,ruleset_version,finalized_by,finalized_at
  ) values(p_class_id,'Finalized','faults_then_time','CCE 2026',auth.uid(),now())
  on conflict(class_id) do update set
    status='Finalized',finalized_by=auth.uid(),finalized_at=now();
  select to_jsonb(j) into strict v_result
  from public.show_office_class_judging j where j.class_id=p_class_id;
  return v_result;
end;
$$;

create or replace function public.cce_reopen_show_office_class(p_class_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_result jsonb;
begin
  if not public.cce_has_permission('show_office.judging.reopen') then
    raise exception 'Permission denied: Show Office judging reopen permission is required'
      using errcode='42501';
  end if;
  update public.show_office_class_judging
  set status='Running',finalized_by=null,finalized_at=null
  where class_id=p_class_id and status='Finalized';
