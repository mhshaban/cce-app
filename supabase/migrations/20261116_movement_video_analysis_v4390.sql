-- CCE StableOS v4.39.0 — Video movement analysis (AI aid, not a diagnosis)
-- Builds on v4.38.0 (horse_movement_logs, horse_ride_checks, horse-media).
--
--   * horse_gait_analyses: one AI review of one video attached to a movement
--     observation or a ride check. The browser samples frames from the video,
--     the gait-analysis edge function sends them to Claude and saves the
--     structured result: estimated lameness grade (0-5), suspected leg(s),
--     confidence, recommendation (normal / monitor / vet), findings, notes on
--     video quality, and time-stamped annotations that the app writes over
--     the video while it plays (and into a downloadable copy).
--
-- The result is an aid for the coach and the vet, never a veterinary
-- diagnosis; the app labels it that way.
--
-- Access is the same as the movement log: anyone who can read the log can
-- read its analyses; anyone who can record can request one; only the author
-- or a manager (horse_events.manage) can delete it. Rows are written by the
-- edge function with the caller's own session, so RLS and the author stamp
-- apply as usual. Deleting the observation, check or horse removes its
-- analyses.

begin;

create table if not exists public.horse_gait_analyses(
  id bigint generated by default as identity primary key,
  horse_id bigint not null references public.horses(id) on delete cascade,
  movement_log_id bigint references public.horse_movement_logs(id) on delete cascade,
  ride_check_id bigint references public.horse_ride_checks(id) on delete cascade,
  media_path text not null check (media_path like 'movement/%'),
  gait text not null default 'trot' check (gait in ('walk','trot','canter','lunge','other')),
  view text not null default 'side' check (view in ('side','front','behind','mixed')),
  clip_start numeric(8,2) not null default 0 check (clip_start>=0),
  clip_end numeric(8,2) check (clip_end is null or clip_end>=clip_start),
  frame_count integer not null default 0 check (frame_count between 0 and 64),
  status text not null default 'done' check (status in ('done','failed')),
  grade smallint check (grade is null or grade between 0 and 5),
  suspected_limbs text[] not null default '{}' check (suspected_limbs <@ array['LF','RF','LH','RH']::text[]),
  confidence text check (confidence is null or confidence in ('low','medium','high')),
  recommendation text check (recommendation is null or recommendation in ('normal','monitor','vet')),
  summary_ar text,
  summary_en text,
  result jsonb not null default '{}'::jsonb check (jsonb_typeof(result)='object'),
  annotations jsonb not null default '[]'::jsonb check (jsonb_typeof(annotations)='array'),
  model text,
  input_tokens integer,
  output_tokens integer,
  error text,
  created_by uuid default auth.uid(),
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint horse_gait_analyses_one_parent check (num_nonnulls(movement_log_id,ride_check_id)<=1)
);
create index if not exists horse_gait_analyses_media_idx on public.horse_gait_analyses(media_path,created_at desc);
create index if not exists horse_gait_analyses_horse_idx on public.horse_gait_analyses(horse_id,created_at desc);
create index if not exists horse_gait_analyses_log_idx on public.horse_gait_analyses(movement_log_id) where movement_log_id is not null;
create index if not exists horse_gait_analyses_check_idx on public.horse_gait_analyses(ride_check_id) where ride_check_id is not null;

drop trigger if exists horse_gait_analyses_touch on public.horse_gait_analyses;
create trigger horse_gait_analyses_touch before update on public.horse_gait_analyses
for each row execute function public.cce_touch_updated_at();
drop trigger if exists horse_gait_analyses_author on public.horse_gait_analyses;
create trigger horse_gait_analyses_author before insert or update on public.horse_gait_analyses
for each row execute function public.cce_movement_stamp_author();

alter table public.horse_gait_analyses enable row level security;
revoke all on public.horse_gait_analyses from anon;
grant select,insert,update,delete on public.horse_gait_analyses to authenticated;

drop policy if exists cce_horse_gait_analyses_select on public.horse_gait_analyses;
create policy cce_horse_gait_analyses_select on public.horse_gait_analyses for select to authenticated
  using (public.cce_movement_can_view());
drop policy if exists cce_horse_gait_analyses_insert on public.horse_gait_analyses;
create policy cce_horse_gait_analyses_insert on public.horse_gait_analyses for insert to authenticated
  with check (public.cce_movement_can_record());
drop policy if exists cce_horse_gait_analyses_update on public.horse_gait_analyses;
create policy cce_horse_gait_analyses_update on public.horse_gait_analyses for update to authenticated
  using (public.cce_movement_can_record() and (created_by=auth.uid() or public.cce_has_permission('horse_events.manage')))
  with check (public.cce_movement_can_record());
drop policy if exists cce_horse_gait_analyses_delete on public.horse_gait_analyses;
create policy cce_horse_gait_analyses_delete on public.horse_gait_analyses for delete to authenticated
  using (public.cce_movement_can_record() and (created_by=auth.uid() or public.cce_has_permission('horse_events.manage')));

commit;
