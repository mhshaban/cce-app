-- Authenticated owner access uses the profile mapping and never accepts a password or owner name from the browser.
create or replace function public.cce_member_owner_horses()
returns setof jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare v_owner text;
begin
  if not public.cce_has_permission('owner.horses.view') then raise exception 'Permission denied'; end if;
  select owner_name into v_owner from public.profiles where id=auth.uid() and is_active=true;
  if coalesce(trim(v_owner),'')='' then raise exception 'Owner mapping is missing'; end if;
  return query select to_jsonb(h)-'owner_pwd' from public.horses h
    where lower(trim(h.owner))=lower(trim(v_owner)) order by h.horse_name;
end;
$$;

