-- CCE StableOS v4.34.0 — Paddock occupancy board (جدول البادوكات)
-- Daily paddock schedule for the three paddocks (big / inner / outer):
-- 20-minute daily movement (Lunging / Free), 45-minute sessions, and
-- stable training sessions that carry no horse.
--
-- Privacy contract: the board is read through cce_paddock_board(). Accounts
-- with paddocks.view see every horse. Horse owners (owner.horses.view) see
-- the whole timetable, but horse names only for their own horses; every other
-- occupied slot comes back without horse_id/horse_name/owner/stable_no, so a
-- browser can never learn another owner's horse. The table itself is readable
-- only with paddocks.view, and all writes go through validated RPCs.
--
-- Safe to re-run: the seed only runs while the table is empty.

begin;

do $$
begin
  if to_regclass('public.horses') is null
     or to_regclass('public.profiles') is null
     or to_regclass('public.app_permissions') is null
     or to_regprocedure('public.cce_has_permission(text)') is null then
    raise exception 'CCE unified member portal and RBAC foundation must be applied before the paddock board';
  end if;
end $$;

create table if not exists public.paddock_slots(
  id bigint generated by default as identity primary key,
  paddock text not null,
  start_time time not null,
  end_time time not null,
  activity text not null,
  horse_id bigint references public.horses(id) on delete cascade,
  note text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid(),
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid(),
  constraint paddock_slots_paddock_check check (paddock in ('big','inner','outer')),
  constraint paddock_slots_activity_check check (activity in ('movement','session','stable_session')),
  constraint paddock_slots_time_check check (end_time>start_time),
  constraint paddock_slots_horse_check check (
    (activity='stable_session' and horse_id is null) or (activity<>'stable_session' and horse_id is not null)
  ),
  constraint paddock_slots_note_check check (note is null or char_length(note)<=180)
);
create index if not exists paddock_slots_paddock_start_idx on public.paddock_slots(paddock,start_time);
create index if not exists paddock_slots_horse_idx on public.paddock_slots(horse_id);

comment on table public.paddock_slots is
  'Daily paddock occupancy (v4.34.0). Read with paddocks.view or through cce_paddock_board(); write only through cce_paddock_save_slot/cce_paddock_delete_slot.';

insert into public.app_permissions(code,category,name_en,name_ar) values
('paddocks.view','Paddocks','View the full paddock board','عرض جدول البادوكات كاملاً'),
('paddocks.manage','Paddocks','Manage paddock slots','إدارة جدول البادوكات')
on conflict(code) do update set category=excluded.category,name_en=excluded.name_en,name_ar=excluded.name_ar;

insert into public.role_permissions(role_id,permission_code,allowed)
select r.id,p.code,true from public.app_roles r
join public.app_permissions p on p.code in ('paddocks.view','paddocks.manage')
where r.code in ('super_admin','manager')
on conflict(role_id,permission_code) do update set allowed=true;

alter table public.paddock_slots enable row level security;
revoke all on public.paddock_slots from anon,authenticated;
grant select on public.paddock_slots to authenticated;
drop policy if exists cce_paddock_slots_select on public.paddock_slots;
create policy cce_paddock_slots_select on public.paddock_slots for select to authenticated
using (public.cce_has_permission('paddocks.view'));

-- ---------------------------------------------------------------------------
-- Read: full board for paddocks.view, masked board for owners
-- ---------------------------------------------------------------------------
create or replace function public.cce_paddock_board()
returns jsonb
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
declare
  v_full boolean:=public.cce_has_permission('paddocks.view');
  v_owner text;
  v_slots jsonb;
begin
  if not v_full and not public.cce_has_permission('owner.horses.view') then
    raise exception 'Permission denied';
  end if;

  if not v_full then
    select owner_name into v_owner from public.profiles where id=auth.uid() and is_active=true;
  end if;

  select coalesce(jsonb_agg(
    case when s.visible then jsonb_build_object(
      'id',s.id,'paddock',s.paddock,'start_time',to_char(s.start_time,'HH24:MI'),'end_time',to_char(s.end_time,'HH24:MI'),
      'activity',s.activity,'mine',s.mine,'reserved',false,
      'horse_id',s.horse_id,'horse_name',trim(s.horse_name),'owner',s.owner,'stable_no',s.stable_no,
      'note',case when v_full then s.note end
    ) else jsonb_build_object(
      'id',s.id,'paddock',s.paddock,'start_time',to_char(s.start_time,'HH24:MI'),'end_time',to_char(s.end_time,'HH24:MI'),
      'activity',s.activity,'mine',false,'reserved',true
    ) end
    order by s.paddock,s.start_time
  ),'[]'::jsonb)
  into v_slots
  from (
    select ps.*,h.horse_name,h.owner,h.stable_no,
      coalesce(h.id is not null and (
        h.owner_profile_id=auth.uid()
        or (h.owner_profile_id is null and coalesce(trim(v_owner),'')<>'' and lower(trim(h.owner))=lower(trim(v_owner)))
      ),false) as mine,
      (v_full or (h.id is not null and (
        h.owner_profile_id=auth.uid()
        or (h.owner_profile_id is null and coalesce(trim(v_owner),'')<>'' and lower(trim(h.owner))=lower(trim(v_owner)))
      ))) as visible
    from public.paddock_slots ps
    left join public.horses h on h.id=ps.horse_id
  ) s;

  return jsonb_build_object('full',v_full,'slots',v_slots);
end;
$$;

-- ---------------------------------------------------------------------------
-- Write: validated create/update and delete
-- ---------------------------------------------------------------------------
create or replace function public.cce_paddock_save_slot(
  p_id bigint default null,
  p_paddock text default null,
  p_start_time time default null,
  p_end_time time default null,
  p_activity text default null,
  p_horse_id bigint default null,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_row public.paddock_slots;
  v_horse bigint:=case when p_activity='stable_session' then null else p_horse_id end;
  v_note text:=nullif(trim(coalesce(p_note,'')),'');
begin
  if not public.cce_has_permission('paddocks.manage') then
    raise exception 'Permission denied';
  end if;
  if p_paddock is null or p_paddock not in ('big','inner','outer') then
    raise exception 'Choose a paddock: big, inner or outer' using errcode='22023';
  end if;
  if p_activity is null or p_activity not in ('movement','session','stable_session') then
    raise exception 'Choose an activity: movement, session or stable_session' using errcode='22023';
  end if;
  if p_start_time is null or p_end_time is null or p_end_time<=p_start_time then
    raise exception 'End time must be after start time' using errcode='22023';
  end if;
  if p_activity<>'stable_session' then
    if v_horse is null then
      raise exception 'Choose a horse for this slot' using errcode='22023';
    end if;
    if not exists(select 1 from public.horses where id=v_horse and status='Available') then
      raise exception 'Horse not found or not active' using errcode='P0002';
    end if;
    if exists(
      select 1 from public.paddock_slots
      where horse_id=v_horse and id<>coalesce(p_id,-1)
        and start_time<p_end_time and end_time>p_start_time
    ) then
      raise exception 'This horse already has a paddock slot at that time' using errcode='23P01';
    end if;
  end if;
  if exists(
    select 1 from public.paddock_slots
    where paddock=p_paddock and id<>coalesce(p_id,-1)
      and start_time<p_end_time and end_time>p_start_time
  ) then
    raise exception 'The paddock is already booked at that time' using errcode='23P01';
  end if;

  if p_id is null then
    insert into public.paddock_slots(paddock,start_time,end_time,activity,horse_id,note,created_by,updated_by)
    values(p_paddock,p_start_time,p_end_time,p_activity,v_horse,v_note,auth.uid(),auth.uid())
    returning * into v_row;
  else
    update public.paddock_slots set
      paddock=p_paddock,start_time=p_start_time,end_time=p_end_time,activity=p_activity,
      horse_id=v_horse,note=v_note,updated_at=now(),updated_by=auth.uid()
    where id=p_id
    returning * into v_row;
    if v_row.id is null then
      raise exception 'Paddock slot not found' using errcode='P0002';
    end if;
  end if;

  return to_jsonb(v_row);
end;
$$;

create or replace function public.cce_paddock_delete_slot(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if not public.cce_has_permission('paddocks.manage') then
    raise exception 'Permission denied';
  end if;
  delete from public.paddock_slots where id=p_id;
  if not found then
    raise exception 'Paddock slot not found' using errcode='P0002';
  end if;
  return jsonb_build_object('id',p_id,'deleted',true);
end;
$$;

revoke all on function public.cce_paddock_board() from public,anon;
revoke all on function public.cce_paddock_save_slot(bigint,text,time,time,text,bigint,text) from public,anon;
revoke all on function public.cce_paddock_delete_slot(bigint) from public,anon;
grant execute on function public.cce_paddock_board() to authenticated;
grant execute on function public.cce_paddock_save_slot(bigint,text,time,time,text,bigint,text) to authenticated;
grant execute on function public.cce_paddock_delete_slot(bigint) to authenticated;

comment on function public.cce_paddock_board() is
  'Paddock board. paddocks.view sees every horse; owner.horses.view sees all slot times but horse details only for linked horses (others reserved=true).';
