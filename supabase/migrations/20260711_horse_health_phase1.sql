select r.id,p.code,true from public.app_roles r join public.app_permissions p on p.code in (
'horse_health.view','horse_medical.view','horse_medical.manage','horse_vaccinations.view','horse_care.view','horse_care.manage'
) where r.code in ('trainer','staff')
on conflict (role_id,permission_code) do nothing;

