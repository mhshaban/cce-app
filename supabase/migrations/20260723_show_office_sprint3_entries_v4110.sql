create or replace function public.cce_show_office_stamp_entry_record()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if tg_op='INSERT' then
    new.created_by=auth.uid();
    new.created_at=coalesce(new.created_at,now());
  else
    new.created_by=old.created_by;
    new.created_at=old.created_at;
  end if;
  new.updated_by=auth.uid();
  new.updated_at=now();
  return new;
end;
$$;

create or replace function public.cce_show_office_sync_core_horse_name()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if new.core_horse_id is not null then
    select trim(h.horse_name) into new.horse_name
    from public.horses h where h.id=new.core_horse_id;
    if not found then raise exception 'Core horse not found' using errcode='23503'; end if;
  else
    new.horse_name=trim(new.horse_name);
  end if;
  return new;
end;
$$;

