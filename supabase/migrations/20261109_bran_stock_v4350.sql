  foreach t in array array['feed_settings','feed_accounts','feed_ledger'] loop
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_select',t);
    execute format('create policy %I on public.%I for select to authenticated using (public.cce_has_permission(''feed.view'') or public.cce_has_permission(''feed.manage''))','cce_'||t||'_select',t);
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_write',t);
    execute format('create policy %I on public.%I for all to authenticated using (public.cce_has_permission(''feed.manage'')) with check (public.cce_has_permission(''feed.manage''))','cce_'||t||'_write',t);
  end loop;
end $$;

-- One account for one month: share, issues, own-stock use and running balance.
-- The own balance runs from the account's first ledger month: each month adds
-- purchases and adjustments and takes away whatever was issued above the share.
create or replace function public.cce_feed_account_month(p_account_id bigint,p_month date)
returns jsonb
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
declare
  v_acc public.feed_accounts%rowtype;
  v_month date:=date_trunc('month',p_month)::date;
  v_stable numeric;
  v_total int;
  v_horses jsonb;
  v_count int;
  v_alloc numeric;
  v_first date;
  v_open numeric:=0;
  v_row record;
  v_result jsonb;
begin
  select * into v_acc from public.feed_accounts where id=p_account_id;
  if not found then return null; end if;
  select stable_monthly_bags into v_stable from public.feed_settings where item=v_acc.item;
  select count(*) into v_total from public.horses where status='Available';
  select coalesce(jsonb_agg(jsonb_build_object('horse_name',trim(h.horse_name),'owner',h.owner,'stable_no',h.stable_no) order by h.stable_no,h.horse_name),'[]'::jsonb),count(*)
    into v_horses,v_count
  from public.horses h
  where h.status='Available' and lower(trim(h.owner))=any(select lower(trim(o)) from unnest(v_acc.owners) o);
  v_alloc:=coalesce(v_acc.monthly_allocation,round(coalesce(v_stable,0)*v_count/nullif(v_total,0),1),0);

  select date_trunc('month',min(entry_date))::date into v_first from public.feed_ledger where account_id=v_acc.id;
  v_first:=least(coalesce(v_first,v_month),v_month);

  for v_row in
    select m::date as month,
      coalesce(sum(l.qty) filter (where l.kind='issue'),0) as issued,
      coalesce(sum(l.qty) filter (where l.kind='purchase'),0) as purchased,
      coalesce(sum(l.qty) filter (where l.kind='adjust'),0) as adjusted
    from generate_series(v_first,v_month,interval '1 month') m
    left join public.feed_ledger l on l.account_id=v_acc.id and date_trunc('month',l.entry_date)=m
    group by m order by m
  loop
    if v_row.month<v_month then
      v_open:=v_open+v_row.purchased+v_row.adjusted-greatest(v_row.issued-v_alloc,0);
    else
      v_result:=jsonb_build_object(
        'id',v_acc.id,'name',v_acc.name,'item',v_acc.item,'owners',to_jsonb(v_acc.owners),
        'month',to_char(v_month,'YYYY-MM'),'horses',v_horses,'horse_count',v_count,
        'stable_monthly_bags',v_stable,'total_horses',v_total,
        'allocation',v_alloc,'allocation_fixed',v_acc.monthly_allocation is not null,
        'issued',v_row.issued,'purchased',v_row.purchased,'adjusted',v_row.adjusted,
        'from_own',greatest(v_row.issued-v_alloc,0),'allocation_left',greatest(v_alloc-v_row.issued,0),
        'opening_balance',v_open,
        'closing_balance',v_open+v_row.purchased+v_row.adjusted-greatest(v_row.issued-v_alloc,0),
        'entries',coalesce((select jsonb_agg(jsonb_build_object('id',l.id,'date',to_char(l.entry_date,'YYYY-MM-DD'),'kind',l.kind,'qty',l.qty,'note',l.note) order by l.entry_date,l.id)
          from public.feed_ledger l where l.account_id=v_acc.id and date_trunc('month',l.entry_date)=v_month),'[]'::jsonb));
    end if;
  end loop;
  return v_result;
end;
$$;

-- The month's summary as the caller may see it: managers see every active
-- account; an owner sees only accounts their own horses belong to.
create or replace function public.cce_feed_summary(p_month date default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
declare
  v_month date:=date_trunc('month',coalesce(p_month,timezone('Asia/Bahrain',now())::date))::date;
  v_full boolean:=public.cce_has_permission('feed.view') or public.cce_has_permission('feed.manage');
  v_owner text;
begin
  if not v_full and not public.cce_has_permission('owner.horses.view') then
    raise exception 'Permission denied';
  end if;
  select nullif(trim(owner_name),'') into v_owner from public.profiles where id=auth.uid() and is_active=true;
  return jsonb_build_object(
    'month',to_char(v_month,'YYYY-MM'),
    'stable_monthly_bags',(select stable_monthly_bags from public.feed_settings where item='Bran'),
    'accounts',coalesce((
      select jsonb_agg(public.cce_feed_account_month(a.id,v_month) order by a.name)
      from public.feed_accounts a
      where a.active and (v_full or exists(
        select 1 from public.horses h
        where lower(trim(h.owner))=any(select lower(trim(o)) from unnest(a.owners) o)
          and (h.owner_profile_id=auth.uid()
            or (h.owner_profile_id is null and v_owner is not null and lower(trim(h.owner))=lower(v_owner)))))
    ),'[]'::jsonb));
end;
$$;

revoke all on function public.cce_feed_account_month(bigint,date) from public,anon,authenticated;
revoke all on function public.cce_feed_summary(date) from public,anon;
grant execute on function public.cce_feed_summary(date) to authenticated;

