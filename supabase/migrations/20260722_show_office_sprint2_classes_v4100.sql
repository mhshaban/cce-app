  on public.show_office_classes(competition_id,sort_order,id);
create index if not exists show_office_classes_type_idx
  on public.show_office_classes(competition_type);

create or replace function public.cce_show_office_stamp_class()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if tg_op='INSERT' then
    new.created_by=auth.uid();
    new.created_at=coalesce(new.created_at,now());
  else
    new.created_by=old.created_by;
    new.created_at=old.created_at;
  end if;
  new.updated_by=auth.uid();
  new.updated_at=now();
  return new;
end;
$$;

