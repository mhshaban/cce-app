create or replace function public.cce_restore_show_office_entry_data(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_riders jsonb:=coalesce(p_payload->'riders','[]'::jsonb);
  v_horses jsonb:=coalesce(p_payload->'horses','[]'::jsonb);
  v_stables jsonb:=coalesce(p_payload->'stables','[]'::jsonb);
  v_entries jsonb:=coalesce(p_payload->'entries','[]'::jsonb);
  v_row jsonb;
  v_ref uuid;
  v_stable_ref uuid;
  v_date date;
  v_class_id bigint;
  v_rider_id bigint;
  v_horse_id bigint;
  v_stable_id bigint;
  v_inserted_id bigint;
  v_rider_total integer:=0; v_rider_imported integer:=0; v_rider_duplicates integer:=0;
  v_horse_total integer:=0; v_horse_imported integer:=0; v_horse_duplicates integer:=0;
  v_stable_total integer:=0; v_stable_imported integer:=0; v_stable_duplicates integer:=0;
  v_entry_total integer:=0; v_entry_imported integer:=0; v_entry_duplicates integer:=0;
begin
  if jsonb_typeof(v_riders)<>'array' or jsonb_typeof(v_horses)<>'array'
     or jsonb_typeof(v_stables)<>'array' or jsonb_typeof(v_entries)<>'array' then
    raise exception 'Show Office riders, horses, stables and entries must be JSON arrays' using errcode='22023';
  end if;
  v_rider_total:=jsonb_array_length(v_riders);
  v_horse_total:=jsonb_array_length(v_horses);
  v_stable_total:=jsonb_array_length(v_stables);
  v_entry_total:=jsonb_array_length(v_entries);
  if v_rider_total+v_horse_total+v_stable_total+v_entry_total>0
     and not public.cce_has_permission('show_office.entries.create') then
    raise exception 'Permission denied: Show Office entry create permission is required' using errcode='42501';
  end if;

  for v_row in select value from jsonb_array_elements(v_riders) loop
    if jsonb_typeof(v_row)<>'object' or jsonb_typeof(v_row->'rider_ref')<>'string'
       or jsonb_typeof(v_row->'rider_name')<>'string' then
      raise exception 'Show Office backup rider has an invalid structure' using errcode='22023';
    end if;
    begin v_ref:=(v_row->>'rider_ref')::uuid; exception when others then
      raise exception 'Show Office backup rider has an invalid rider_ref' using errcode='22023'; end;
    if length(trim(v_row->>'rider_name'))=0 or char_length(trim(v_row->>'rider_name'))>180 then
      raise exception 'Show Office backup rider has an invalid rider_name' using errcode='22023';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_riders(rider_ref,rider_name)
    values(v_ref,trim(v_row->>'rider_name')) on conflict do nothing returning id into v_inserted_id;
    if v_inserted_id is null then v_rider_duplicates:=v_rider_duplicates+1; else v_rider_imported:=v_rider_imported+1; end if;
  end loop;

  for v_row in select value from jsonb_array_elements(v_horses) loop
    if jsonb_typeof(v_row)<>'object' or jsonb_typeof(v_row->'horse_ref')<>'string'
       or jsonb_typeof(v_row->'horse_name')<>'string' then
      raise exception 'Show Office backup horse has an invalid structure' using errcode='22023';
    end if;
    begin v_ref:=(v_row->>'horse_ref')::uuid; exception when others then
      raise exception 'Show Office backup horse has an invalid horse_ref' using errcode='22023'; end;
    if length(trim(v_row->>'horse_name'))=0 or char_length(trim(v_row->>'horse_name'))>180 then
      raise exception 'Show Office backup horse has an invalid horse_name' using errcode='22023';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_horses(horse_ref,horse_name)
    values(v_ref,trim(v_row->>'horse_name')) on conflict do nothing returning id into v_inserted_id;
    if v_inserted_id is null then v_horse_duplicates:=v_horse_duplicates+1; else v_horse_imported:=v_horse_imported+1; end if;
  end loop;

  for v_row in select value from jsonb_array_elements(v_stables) loop
    if jsonb_typeof(v_row)<>'object' or jsonb_typeof(v_row->'stable_ref')<>'string'
       or jsonb_typeof(v_row->'stable_name')<>'string' then
      raise exception 'Show Office backup stable has an invalid structure' using errcode='22023';
    end if;
    begin v_ref:=(v_row->>'stable_ref')::uuid; exception when others then
      raise exception 'Show Office backup stable has an invalid stable_ref' using errcode='22023'; end;
    if length(trim(v_row->>'stable_name'))=0 or char_length(trim(v_row->>'stable_name'))>180 then
      raise exception 'Show Office backup stable has an invalid stable_name' using errcode='22023';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_stables(stable_ref,stable_name)
    values(v_ref,trim(v_row->>'stable_name')) on conflict do nothing returning id into v_inserted_id;
    if v_inserted_id is null then v_stable_duplicates:=v_stable_duplicates+1; else v_stable_imported:=v_stable_imported+1; end if;
  end loop;

  for v_row in select value from jsonb_array_elements(v_entries) loop
    if jsonb_typeof(v_row)<>'object' then raise exception 'Show Office backup entry must be an object' using errcode='22023'; end if;
    begin
      v_ref:=(v_row->>'entry_ref')::uuid;
      v_rider_id=null; v_horse_id=null; v_stable_id=null;
      v_date:=(v_row->>'competition_date')::date;
    exception when others then
      raise exception 'Show Office backup entry has invalid references or date' using errcode='22023';
    end;
    if coalesce(v_row->>'competition_date','')!~'^\d{4}-\d{2}-\d{2}$'
       or to_char(v_date,'YYYY-MM-DD')<>v_row->>'competition_date'
       or length(trim(coalesce(v_row->>'competition_name','')))=0
       or length(trim(coalesce(v_row->>'class_number','')))=0 then
      raise exception 'Show Office backup entry has an invalid class reference' using errcode='22023';
    end if;
    if jsonb_typeof(v_row->'start_number')<>'number'
       or (v_row->>'start_number')::numeric<>trunc((v_row->>'start_number')::numeric)
       or (v_row->>'start_number')::numeric<=0
       or (v_row->>'start_number')::numeric>2147483647 then
      raise exception 'Show Office backup entry has an invalid start_number' using errcode='22023';
    end if;
    begin
      select cl.id into strict v_class_id
      from public.show_office_classes cl
      join public.show_office_competitions c on c.id=cl.competition_id
      where lower(trim(c.competition_name))=lower(trim(v_row->>'competition_name'))
        and c.competition_date=v_date
        and lower(trim(cl.class_number))=lower(trim(v_row->>'class_number'));
    exception when no_data_found then
      raise exception 'Show Office backup entry references an unavailable class' using errcode='23503';
    end;
    select id into v_rider_id from public.show_office_riders where rider_ref=(v_row->>'rider_ref')::uuid;
    if v_rider_id is null then
      select r.id into v_rider_id
      from public.show_office_riders r
      join jsonb_array_elements(v_riders) source
        on (source->>'rider_ref')::uuid=(v_row->>'rider_ref')::uuid
       and lower(trim(r.rider_name))=lower(trim(source->>'rider_name'))
      limit 1;
    end if;
    select id into v_horse_id from public.show_office_horses where horse_ref=(v_row->>'horse_ref')::uuid;
    if v_horse_id is null then
      select h.id into v_horse_id
      from public.show_office_horses h
      join jsonb_array_elements(v_horses) source
        on (source->>'horse_ref')::uuid=(v_row->>'horse_ref')::uuid
       and lower(trim(h.horse_name))=lower(trim(source->>'horse_name'))
      limit 1;
    end if;
    if nullif(v_row->>'stable_ref','') is not null then
      v_stable_ref:=(v_row->>'stable_ref')::uuid;
      select id into v_stable_id from public.show_office_stables where stable_ref=v_stable_ref;
      if v_stable_id is null then
        select s.id into v_stable_id
        from public.show_office_stables s
        join jsonb_array_elements(v_stables) source
          on (source->>'stable_ref')::uuid=v_stable_ref
         and lower(trim(s.stable_name))=lower(trim(source->>'stable_name'))
        limit 1;
      end if;
    end if;
    if v_rider_id is null or v_horse_id is null
       or (nullif(v_row->>'stable_ref','') is not null and v_stable_id is null) then
      raise exception 'Show Office backup entry references an unavailable rider, horse or stable' using errcode='23503';
    end if;
    v_inserted_id:=null;
    insert into public.show_office_entries(entry_ref,class_id,start_number,rider_id,horse_id,stable_id)
    values(v_ref,v_class_id,(v_row->>'start_number')::integer,v_rider_id,v_horse_id,v_stable_id)
    on conflict do nothing returning id into v_inserted_id;
    if v_inserted_id is null then v_entry_duplicates:=v_entry_duplicates+1; else v_entry_imported:=v_entry_imported+1; end if;
  end loop;

  return jsonb_build_object(
    'total',v_rider_total+v_horse_total+v_stable_total+v_entry_total,
    'imported',v_rider_imported+v_horse_imported+v_stable_imported+v_entry_imported,
    'duplicates',v_rider_duplicates+v_horse_duplicates+v_stable_duplicates+v_entry_duplicates,
    'invalid',0,
    'entities',jsonb_build_object(
      'riders',jsonb_build_object('total',v_rider_total,'imported',v_rider_imported,'duplicates',v_rider_duplicates,'invalid',0),
      'horses',jsonb_build_object('total',v_horse_total,'imported',v_horse_imported,'duplicates',v_horse_duplicates,'invalid',0),
      'stables',jsonb_build_object('total',v_stable_total,'imported',v_stable_imported,'duplicates',v_stable_duplicates,'invalid',0),
      'entries',jsonb_build_object('total',v_entry_total,'imported',v_entry_imported,'duplicates',v_entry_duplicates,'invalid',0)
    )
  );
end;
$$;

