create or replace function public.cce_has_permission(p_permission text)
returns boolean
language sql
stable
security definer
set search_path=public
as $$
  select coalesce((
    select case
      when p.is_active is not true then false
      when up.allowed is not null then up.allowed
      when r.code='super_admin' then true
      else coalesce(rp.allowed,false)
    end
    from public.profiles p
    left join public.app_roles r on r.id=p.role_id
    left join public.user_permissions up on up.user_id=p.id and up.permission_code=p_permission
    left join public.role_permissions rp on rp.role_id=p.role_id and rp.permission_code=p_permission
    where p.id=auth.uid()
    limit 1
  ),false);
$$;

create or replace function public.cce_is_booking_record(p_notes text)
returns boolean language sql immutable as $$
