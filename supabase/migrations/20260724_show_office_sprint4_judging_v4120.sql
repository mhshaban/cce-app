create or replace function public.cce_show_office_stamp_judging()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if tg_op='INSERT' then
    new.created_by=auth.uid();
    new.created_at=coalesce(new.created_at,now());
  else
    new.created_by=old.created_by;
    new.created_at=old.created_at;
  end if;
  if new.status<>'Finalized' then
    new.finalized_by=null;
    new.finalized_at=null;
  end if;
  new.updated_by=auth.uid();
  new.updated_at=now();
  return new;
end;
$$;

create or replace function public.cce_show_office_stamp_round()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if tg_op='INSERT' then
    new.created_by=auth.uid();
    new.created_at=coalesce(new.created_at,now());
    new.row_version=1;
  else
    new.result_ref=old.result_ref;
    new.entry_id=old.entry_id;
    new.phase=old.phase;
    new.created_by=old.created_by;
    new.created_at=old.created_at;
    new.row_version=old.row_version+1;
  end if;
  new.updated_by=auth.uid();
  new.updated_at=now();
  return new;
end;
$$;

create or replace function public.cce_show_office_audit_round()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_score_ref uuid;
  v_entry_id bigint;
  v_entry_ref uuid;
  v_phase text;
begin
  if tg_op='INSERT' then
    v_score_ref:=new.result_ref; v_entry_id:=new.entry_id; v_phase:=new.phase;
  else
    v_score_ref:=old.result_ref; v_entry_id:=old.entry_id; v_phase:=old.phase;
  end if;
  select entry_ref into strict v_entry_ref
  from public.show_office_entries where id=v_entry_id;
  insert into public.show_office_score_revisions(
    score_ref,entry_ref,phase,action,before_data,after_data,changed_by
  ) values(
    v_score_ref,v_entry_ref,v_phase,
    case tg_op when 'INSERT' then 'create' when 'UPDATE' then 'update' else 'reset' end,
    case when tg_op='INSERT' then null else to_jsonb(old) end,
    case when tg_op='DELETE' then null else to_jsonb(new) end,
    auth.uid()
  );
  if tg_op='DELETE' then
    return old;
  end if;
  return new;
end;
$$;

