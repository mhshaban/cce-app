begin;

insert into public.app_permissions(code,category,name_en,name_ar) values
('horse_health.view','Horse Health','View horse health profiles','عرض الملفات الصحية للخيل'),
('horse_health.manage','Horse Health','Manage horse health profiles','إدارة الملفات الصحية للخيل'),
('horse_medical.view','Horse Health','View medical records','عرض السجلات الطبية'),
('horse_medical.manage','Horse Health','Manage medical records','إدارة السجلات الطبية'),
('horse_vaccinations.view','Horse Health','View vaccinations','عرض التطعيمات'),
('horse_vaccinations.manage','Horse Health','Manage vaccinations','إدارة التطعيمات'),
