-- CCE StableOS v4.38.0 — Movement & lameness log and ride checks
-- Two records tied to the horse health file:
--
--   * horse_movement_logs: an observation of how a horse moves — which
--     limb(s), severity, when it showed (before / during / after riding or
--     not ridden), symptoms, notes and photo/video attachments. A log can
--     open a veterinary follow-up care task in horse_health_events
--     (source_table='horse_movement_logs'), so it shows in the horse's
--     Care & Alerts and in the alert bell like any other care task.
--   * horse_ride_checks: the coach's pre-ride or post-ride checklist for a
--     horse, optionally tied to a schedule session. Each item is ok or a
--     concern; a post-ride check records the decision (continue, monitor,
--     rest, vet).
--
-- Photos and videos go to the private storage bucket horse-media under
-- movement/<horse_id>/..., readable through signed URLs only.
--
-- Access reuses the horse-care permissions that managers, trainers and
-- staff already hold: horse_care.view (or horse_events.view) to read,
-- horse_care.manage (or horse_events.manage) to record. Only the author or
-- a horse_events.manage holder can edit or delete a record.
-- Safe to re-run.

begin;

do $$
begin
  if to_regclass('public.horses') is null
     or to_regclass('public.horse_health_events') is null
     or to_regprocedure('public.cce_has_permission(text)') is null
     or to_regprocedure('public.cce_touch_updated_at()') is null then
    raise exception 'v4.7.0 horse health foundation must be applied before the movement log';
  end if;
end $$;

create or replace function public.cce_movement_can_view()
returns boolean
language sql
stable
security definer
set search_path=public,pg_temp
as $$
  select public.cce_has_permission('horse_care.view') or public.cce_has_permission('horse_events.view')
    or public.cce_has_permission('horse_care.manage') or public.cce_has_permission('horse_events.manage')
$$;

create or replace function public.cce_movement_can_record()
returns boolean
language sql
stable
security definer
set search_path=public,pg_temp
as $$
  select public.cce_has_permission('horse_care.manage') or public.cce_has_permission('horse_events.manage')
$$;

create table if not exists public.horse_ride_checks(
  id bigint generated by default as identity primary key,
  horse_id bigint not null references public.horses(id) on delete cascade,
  schedule_id bigint references public.schedule(id) on delete set null,
  check_date date not null default (timezone('Asia/Bahrain',now()))::date,
  phase text not null check (phase in ('pre','post')),
  items jsonb not null default '{}'::jsonb check (jsonb_typeof(items)='object'),
  cleared boolean not null default true,
  decision text check (decision is null or decision in ('continue','monitor','rest','vet')),
  notes text,
  media jsonb not null default '[]'::jsonb check (jsonb_typeof(media)='array'),
  health_event_id bigint references public.horse_health_events(id) on delete set null,
  created_by uuid default auth.uid(),
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists horse_ride_checks_horse_date_idx on public.horse_ride_checks(horse_id,check_date desc);
create index if not exists horse_ride_checks_schedule_idx on public.horse_ride_checks(schedule_id) where schedule_id is not null;

create table if not exists public.horse_movement_logs(
  id bigint generated by default as identity primary key,
  horse_id bigint not null references public.horses(id) on delete cascade,
  observed_on date not null default (timezone('Asia/Bahrain',now()))::date,
  limbs text[] not null default '{}' check (limbs <@ array['LF','RF','LH','RH']::text[]),
  severity text not null default 'mild' check (severity in ('none','mild','moderate','severe')),
  onset text check (onset is null or onset in ('before_ride','during_ride','after_ride','not_ridden')),
  symptoms text[] not null default '{}' check (symptoms <@ array['lameness','discomfort','gait_change','stumbling','swelling','heat','other']::text[]),
  notes text,
  media jsonb not null default '[]'::jsonb check (jsonb_typeof(media)='array'),
  ride_check_id bigint references public.horse_ride_checks(id) on delete set null,
  health_event_id bigint references public.horse_health_events(id) on delete set null,
  created_by uuid default auth.uid(),
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists horse_movement_logs_horse_date_idx on public.horse_movement_logs(horse_id,observed_on desc);
create index if not exists horse_movement_logs_date_idx on public.horse_movement_logs(observed_on desc);

drop trigger if exists horse_movement_logs_touch on public.horse_movement_logs;
create trigger horse_movement_logs_touch before update on public.horse_movement_logs
for each row execute function public.cce_touch_updated_at();
drop trigger if exists horse_ride_checks_touch on public.horse_ride_checks;
create trigger horse_ride_checks_touch before update on public.horse_ride_checks
for each row execute function public.cce_touch_updated_at();

-- The author's display name is stamped by the database, not trusted from the client.
create or replace function public.cce_movement_stamp_author()
returns trigger
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if tg_op='INSERT' then
    new.created_by:=coalesce(auth.uid(),new.created_by);
    new.created_by_name:=coalesce((select nullif(trim(full_name),'') from public.profiles where id=auth.uid()),new.created_by_name);
  else
    new.created_by:=old.created_by;
    new.created_by_name:=old.created_by_name;
    new.created_at:=old.created_at;
  end if;
  return new;
end;
$$;
drop trigger if exists horse_movement_logs_author on public.horse_movement_logs;
create trigger horse_movement_logs_author before insert or update on public.horse_movement_logs
for each row execute function public.cce_movement_stamp_author();
drop trigger if exists horse_ride_checks_author on public.horse_ride_checks;
create trigger horse_ride_checks_author before insert or update on public.horse_ride_checks
for each row execute function public.cce_movement_stamp_author();

alter table public.horse_movement_logs enable row level security;
alter table public.horse_ride_checks enable row level security;
revoke all on public.horse_movement_logs,public.horse_ride_checks from anon;
grant select,insert,update,delete on public.horse_movement_logs,public.horse_ride_checks to authenticated;

do $$
declare t text;
begin
  foreach t in array array['horse_movement_logs','horse_ride_checks'] loop
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_select',t);
    execute format('create policy %I on public.%I for select to authenticated using (public.cce_movement_can_view())','cce_'||t||'_select',t);
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_insert',t);
    execute format('create policy %I on public.%I for insert to authenticated with check (public.cce_movement_can_record())','cce_'||t||'_insert',t);
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_update',t);
    execute format('create policy %I on public.%I for update to authenticated using (public.cce_movement_can_record() and (created_by=auth.uid() or public.cce_has_permission(''horse_events.manage''))) with check (public.cce_movement_can_record())','cce_'||t||'_update',t);
    execute format('drop policy if exists %I on public.%I','cce_'||t||'_delete',t);
    execute format('create policy %I on public.%I for delete to authenticated using (public.cce_movement_can_record() and (created_by=auth.uid() or public.cce_has_permission(''horse_events.manage'')))','cce_'||t||'_delete',t);
  end loop;
end $$;

-- Horses a coach or stable hand can pick from (they may not hold horses.view).
create or replace function public.cce_movement_horses()
returns table(id bigint,horse_name text,stable_no text,status text)
language plpgsql
stable
security definer
set search_path=public,pg_temp
as $$
begin
  if not public.cce_movement_can_view() then
    raise exception 'Permission denied';
  end if;
  return query
    select h.id,trim(h.horse_name)::text,h.stable_no::text,h.status::text
    from public.horses h
    where nullif(trim(h.horse_name),'') is not null
    order by (h.status='Available') desc,trim(h.horse_name);
end;
$$;
revoke all on function public.cce_movement_horses() from public,anon;
grant execute on function public.cce_movement_horses() to authenticated;
revoke all on function public.cce_movement_can_view() from public,anon;
revoke all on function public.cce_movement_can_record() from public,anon;
grant execute on function public.cce_movement_can_view() to authenticated;
grant execute on function public.cce_movement_can_record() to authenticated;

-- Private bucket for movement photos and videos (Supabase only; skipped where
-- the storage schema does not exist, e.g. local test databases).
do $$
begin
  if to_regclass('storage.buckets') is null or to_regclass('storage.objects') is null then
    return;
  end if;
  insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
  values('horse-media','horse-media',false,52428800,array['image/*','video/*'])
  on conflict (id) do update set public=false,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;

  execute 'drop policy if exists cce_horse_media_select on storage.objects';
  execute 'create policy cce_horse_media_select on storage.objects for select to authenticated using (bucket_id=''horse-media'' and public.cce_movement_can_view())';
  execute 'drop policy if exists cce_horse_media_insert on storage.objects';
  execute 'create policy cce_horse_media_insert on storage.objects for insert to authenticated with check (bucket_id=''horse-media'' and public.cce_movement_can_record())';
  execute 'drop policy if exists cce_horse_media_delete on storage.objects';
  execute 'create policy cce_horse_media_delete on storage.objects for delete to authenticated using (bucket_id=''horse-media'' and public.cce_movement_can_record() and (owner_id=auth.uid()::text or public.cce_has_permission(''horse_events.manage'')))';
end $$;

commit;
