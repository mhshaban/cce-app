create table if not exists public.show_office_classes (
  id bigint generated by default as identity primary key,
  competition_id bigint not null references public.show_office_competitions(id) on delete restrict,
  class_number text not null,
  sort_order integer not null,
  class_name text not null,
  height_cm smallint,
  competition_type text not null,
  allowed_time_seconds integer,
  time_limit_seconds integer,
  jump_off boolean not null default false,
  entry_fee_bd numeric(10,3) not null default 0,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint show_office_classes_number_required check (length(trim(class_number))>0),
  constraint show_office_classes_number_length_check check (char_length(trim(class_number))<=30),
  constraint show_office_classes_sort_order_check check (sort_order>0),
  constraint show_office_classes_name_required check (length(trim(class_name))>0),
  constraint show_office_classes_name_length_check check (char_length(trim(class_name))<=180),
  constraint show_office_classes_height_check check (height_cm is null or height_cm>0),
  constraint show_office_classes_type_required check (length(trim(competition_type))>0),
  constraint show_office_classes_type_length_check check (char_length(trim(competition_type))<=120),
  constraint show_office_classes_allowed_time_check check (allowed_time_seconds is null or allowed_time_seconds>0),
  constraint show_office_classes_time_limit_check check (time_limit_seconds is null or time_limit_seconds>0),
  constraint show_office_classes_time_order_check check (
    allowed_time_seconds is null or time_limit_seconds is null or time_limit_seconds>=allowed_time_seconds
  ),
  constraint show_office_classes_entry_fee_check check (entry_fee_bd>=0),
  constraint show_office_classes_notes_length_check check (char_length(coalesce(notes,''))<=4000)
);

create unique index if not exists show_office_classes_competition_number_uidx
