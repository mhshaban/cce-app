create or replace function public.cce_show_office_entry_context()
returns table(
  competition_id bigint,competition_name text,competition_date date,
  class_id bigint,class_number text,class_name text,sort_order integer
)
language plpgsql
stable
security definer
set search_path=public
as $$
begin
  if not (
    public.cce_has_permission('show_office.view')
    or public.cce_has_permission('show_office.entries.view')
    or public.cce_has_permission('show_office.entries.create')
    or public.cce_has_permission('show_office.entries.update')
  ) then
    raise exception 'Permission denied: Show Office entry permission is required' using errcode='42501';
  end if;
  return query
  select c.id,c.competition_name,c.competition_date,
         cl.id,cl.class_number,cl.class_name,cl.sort_order
  from public.show_office_competitions c
  join public.show_office_classes cl on cl.competition_id=c.id
  order by c.competition_date desc,c.id desc,cl.sort_order,cl.id;
end;
$$;

create or replace function public.cce_show_office_entry_directory(
  p_query text default '',p_limit integer default 50
)
returns jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare
  v_query text:=lower(trim(coalesce(p_query,'')));
  v_limit integer:=greatest(1,least(coalesce(p_limit,50),100));
begin
  if not (
    public.cce_has_permission('show_office.view')
    or public.cce_has_permission('show_office.entries.view')
    or public.cce_has_permission('show_office.entries.create')
    or public.cce_has_permission('show_office.entries.update')
  ) then
    raise exception 'Permission denied: Show Office entry permission is required' using errcode='42501';
  end if;
  return jsonb_build_object(
    'riders',coalesce((select jsonb_agg(to_jsonb(x) order by x.rider_name,x.id) from (
      select r.id,r.rider_ref,r.rider_name from public.show_office_riders r
      where v_query='' or lower(r.rider_name) like '%'||v_query||'%'
      order by r.rider_name,r.id limit v_limit
    ) x),'[]'::jsonb),
    'horses',coalesce((select jsonb_agg(to_jsonb(x) order by x.horse_name,x.id) from (
      select h.id,h.horse_ref,h.core_horse_id,h.horse_name from public.show_office_horses h
      where v_query='' or lower(h.horse_name) like '%'||v_query||'%'
      order by h.horse_name,h.id limit v_limit
    ) x),'[]'::jsonb),
    'stables',coalesce((select jsonb_agg(to_jsonb(x) order by x.stable_name,x.id) from (
      select s.id,s.stable_ref,s.stable_name from public.show_office_stables s
      where v_query='' or lower(s.stable_name) like '%'||v_query||'%'
      order by s.stable_name,s.id limit v_limit
    ) x),'[]'::jsonb),
    'core_horses',coalesce((select jsonb_agg(to_jsonb(x) order by x.horse_name,x.id) from (
      select h.id,h.horse_name,h.stable_no from public.horses h
      where length(trim(coalesce(h.horse_name,'')))>0
        and (v_query='' or lower(h.horse_name) like '%'||v_query||'%'
          or lower(coalesce(h.stable_no,'')) like '%'||v_query||'%')
      order by h.horse_name,h.id limit v_limit
    ) x),'[]'::jsonb)
  );
end;
$$;

create or replace function public.cce_show_office_entries_page(
  p_class_id bigint,p_search text default '',p_limit integer default 100,p_offset integer default 0
)
returns jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare
  v_search text:=lower(trim(coalesce(p_search,'')));
  v_limit integer:=greatest(1,least(coalesce(p_limit,100),200));
  v_offset integer:=greatest(0,coalesce(p_offset,0));
  v_total integer;
  v_rows jsonb;
begin
  if not (public.cce_has_permission('show_office.view') or public.cce_has_permission('show_office.entries.view')) then
    raise exception 'Permission denied: Show Office entry view permission is required' using errcode='42501';
  end if;
  if not exists(select 1 from public.show_office_classes where id=p_class_id) then
    raise exception 'Competition class not found' using errcode='23503';
  end if;
  select count(*) into v_total
  from public.show_office_entries e
  join public.show_office_riders r on r.id=e.rider_id
  join public.show_office_horses h on h.id=e.horse_id
  left join public.show_office_stables s on s.id=e.stable_id
  where e.class_id=p_class_id and (
    v_search='' or e.start_number::text like '%'||v_search||'%'
    or lower(r.rider_name) like '%'||v_search||'%'
    or lower(h.horse_name) like '%'||v_search||'%'
    or lower(coalesce(s.stable_name,'')) like '%'||v_search||'%'
  );
  select coalesce(jsonb_agg(to_jsonb(x) order by x.start_number,x.id),'[]'::jsonb) into v_rows
  from (
    select e.id,e.entry_ref,e.class_id,e.start_number,e.rider_id,r.rider_name,
           e.horse_id,h.horse_name,e.stable_id,s.stable_name,e.created_at,e.updated_at
    from public.show_office_entries e
    join public.show_office_riders r on r.id=e.rider_id
    join public.show_office_horses h on h.id=e.horse_id
    left join public.show_office_stables s on s.id=e.stable_id
    where e.class_id=p_class_id and (
      v_search='' or e.start_number::text like '%'||v_search||'%'
      or lower(r.rider_name) like '%'||v_search||'%'
      or lower(h.horse_name) like '%'||v_search||'%'
      or lower(coalesce(s.stable_name,'')) like '%'||v_search||'%'
    )
    order by e.start_number,e.id limit v_limit offset v_offset
  ) x;
  return jsonb_build_object('total',v_total,'rows',v_rows,'limit',v_limit,'offset',v_offset);
end;
$$;

create or replace function public.cce_save_show_office_entry(
  p_class_id bigint,
  p_start_number integer,
  p_entry_id bigint default null,
  p_rider_id bigint default null,
  p_rider_name text default null,
  p_horse_id bigint default null,
  p_core_horse_id bigint default null,
  p_horse_name text default null,
  p_stable_id bigint default null,
  p_stable_name text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_rider_id bigint;
  v_horse_id bigint;
  v_stable_id bigint;
  v_entry_id bigint;
  v_name text;
  v_result jsonb;
begin
  if p_entry_id is null then
    if not public.cce_has_permission('show_office.entries.create') then
      raise exception 'Permission denied: Show Office entry create permission is required' using errcode='42501';
    end if;
  else
    if not public.cce_has_permission('show_office.entries.update') then
      raise exception 'Permission denied: Show Office entry update permission is required' using errcode='42501';
    end if;
    if not exists(select 1 from public.show_office_entries where id=p_entry_id) then
      raise exception 'Competition entry not found' using errcode='P0002';
    end if;
  end if;
  if not exists(select 1 from public.show_office_classes where id=p_class_id) then
    raise exception 'Competition class not found' using errcode='23503';
  end if;
  if p_start_number is null or p_start_number<=0 then
    raise exception 'Start number must be a positive whole number' using errcode='22023';
  end if;

  if p_rider_id is not null then
    select id into v_rider_id from public.show_office_riders where id=p_rider_id;
    if v_rider_id is null then raise exception 'Rider not found' using errcode='23503'; end if;
  else
    v_name:=trim(coalesce(p_rider_name,''));
    if v_name='' or char_length(v_name)>180 then raise exception 'A valid rider name is required' using errcode='22023'; end if;
    insert into public.show_office_riders(rider_name) values(v_name)
    on conflict do nothing returning id into v_rider_id;
    if v_rider_id is null then
      select id into v_rider_id from public.show_office_riders where lower(trim(rider_name))=lower(v_name);
    end if;
  end if;

  if p_horse_id is not null then
    select id into v_horse_id from public.show_office_horses where id=p_horse_id;
    if v_horse_id is null then raise exception 'Horse not found' using errcode='23503'; end if;
  elsif p_core_horse_id is not null then
    insert into public.show_office_horses(core_horse_id,horse_name)
    select h.id,h.horse_name from public.horses h where h.id=p_core_horse_id
    on conflict do nothing
    returning id into v_horse_id;
    if v_horse_id is null then
      select sh.id into v_horse_id
      from public.show_office_horses sh
      join public.horses h on h.id=p_core_horse_id
      where sh.core_horse_id=p_core_horse_id or lower(trim(sh.horse_name))=lower(trim(h.horse_name))
      order by (sh.core_horse_id=p_core_horse_id) desc limit 1;
    end if;
    if v_horse_id is null then raise exception 'Core horse not found' using errcode='23503'; end if;
  else
    v_name:=trim(coalesce(p_horse_name,''));
    if v_name='' or char_length(v_name)>180 then raise exception 'A valid horse name is required' using errcode='22023'; end if;
    insert into public.show_office_horses(horse_name) values(v_name)
    on conflict do nothing returning id into v_horse_id;
    if v_horse_id is null then
      select id into v_horse_id from public.show_office_horses where lower(trim(horse_name))=lower(v_name);
    end if;
  end if;

  if p_stable_id is not null then
    select id into v_stable_id from public.show_office_stables where id=p_stable_id;
    if v_stable_id is null then raise exception 'Stable or club not found' using errcode='23503'; end if;
  elsif trim(coalesce(p_stable_name,''))<>'' then
    v_name:=trim(p_stable_name);
    if char_length(v_name)>180 then raise exception 'Stable or club name must be 180 characters or fewer' using errcode='22023'; end if;
    insert into public.show_office_stables(stable_name) values(v_name)
    on conflict do nothing returning id into v_stable_id;
    if v_stable_id is null then
      select id into v_stable_id from public.show_office_stables where lower(trim(stable_name))=lower(v_name);
    end if;
  end if;

  if p_entry_id is null then
    insert into public.show_office_entries(class_id,start_number,rider_id,horse_id,stable_id)
    values(p_class_id,p_start_number,v_rider_id,v_horse_id,v_stable_id)
    returning id into v_entry_id;
  else
    update public.show_office_entries set
      class_id=p_class_id,start_number=p_start_number,rider_id=v_rider_id,
      horse_id=v_horse_id,stable_id=v_stable_id
    where id=p_entry_id returning id into v_entry_id;
  end if;

  select to_jsonb(x) into v_result from (
    select e.id,e.entry_ref,e.class_id,e.start_number,e.rider_id,r.rider_name,
           e.horse_id,h.horse_name,e.stable_id,s.stable_name,e.created_at,e.updated_at
    from public.show_office_entries e
    join public.show_office_riders r on r.id=e.rider_id
    join public.show_office_horses h on h.id=e.horse_id
    left join public.show_office_stables s on s.id=e.stable_id
    where e.id=v_entry_id
  ) x;
  return v_result;
end;
$$;

